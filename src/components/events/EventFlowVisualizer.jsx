import React, { useState } from 'react';
import SectionHeading from '../common/SectionHeading';
import ConceptCard from '../common/ConceptCard';
import { MousePointerClick, Keyboard, CheckCircle2, ArrowDown, Activity } from 'lucide-react';

export default function EventFlowVisualizer({ commonEvents, eventObjectProperties }) {
  const [lastEvent, setLastEvent] = useState({
    type: 'click',
    target: '<button#demo-btn>',
    key: 'N/A',
    timeStamp: '1240.50ms',
    defaultPrevented: false,
  });

  const [counter, setCounter] = useState(0);

  const handleClick = (e) => {
    setCounter((c) => c + 1);
    setLastEvent({
      type: 'click',
      target: `<button id="demo-btn">`,
      key: 'N/A (Mouse click)',
      timeStamp: `${e.timeStamp.toFixed(2)}ms`,
      defaultPrevented: false,
    });
  };

  const handleKeyDown = (e) => {
    setLastEvent({
      type: 'keydown',
      target: `<input name="search">`,
      key: `"${e.key}" (code: ${e.code})`,
      timeStamp: `${e.timeStamp.toFixed(2)}ms`,
      defaultPrevented: false,
    });
  };

  return (
    <section className="scroll-mt-24">
      <SectionHeading
        stepNumber="3"
        title="Interactive Event Listener & Object Inspector"
        subtitle="Interact with elements and inspect the Event Object (e) generated by the browser."
      />

      <div className="grid grid-cols-1 lg:grid-cols-12 gap-6">
        {/* Interaction Trigger Area */}
        <div className="lg:col-span-6 space-y-4">
          <ConceptCard glow={true}>
            <span className="text-xs font-mono font-bold text-slate-300 uppercase block mb-3">
              Trigger Browser User Actions
            </span>

            <div className="space-y-4">
              {/* Button Click Trigger */}
              <div className="p-4 rounded-xl bg-atlas-950 border border-slate-800 space-y-2">
                <span className="text-[10px] font-mono text-slate-400 block">
                  Action 1: Mouse Click Event
                </span>
                <button
                  id="demo-btn"
                  onClick={handleClick}
                  className="w-full py-2.5 bg-gradient-to-r from-sky-500 to-indigo-500 hover:from-sky-400 hover:to-indigo-400 text-white font-mono text-xs font-bold rounded-xl shadow-glow-sm flex items-center justify-center gap-2 transition-all hover:scale-[1.02]"
                >
                  <MousePointerClick className="w-4 h-4" />
                  <span>Click Me! (Clicks: {counter})</span>
                </button>
              </div>

              {/* Keyboard Input Trigger */}
              <div className="p-4 rounded-xl bg-atlas-950 border border-slate-800 space-y-2">
                <span className="text-[10px] font-mono text-slate-400 block">
                  Action 2: Keyboard input Event
                </span>
                <input
                  type="text"
                  onKeyDown={handleKeyDown}
                  placeholder="Type any key here to inspect e.key..."
                  className="w-full bg-atlas-900 border border-slate-700 rounded-xl px-3 py-2 text-xs font-mono text-white placeholder-slate-500 focus:outline-none focus:border-brand-indigo"
                />
              </div>
            </div>
          </ConceptCard>
        </div>

        {/* Live Event Object (e) Inspector */}
        <div className="lg:col-span-6">
          <ConceptCard glow={true} className="h-full flex flex-col justify-between bg-atlas-900">
            <div>
              <div className="flex items-center justify-between pb-3 border-b border-atlas-border mb-4">
                <div className="flex items-center gap-2">
                  <Activity className="w-4 h-4 text-emerald-400" />
                  <span className="text-xs font-mono font-bold text-white uppercase">
                    Captured Event Object (e)
                  </span>
                </div>
                <span className="text-[10px] font-mono text-emerald-400 bg-emerald-950 px-2 py-0.5 rounded border border-emerald-500/30">
                  Event: {lastEvent.type}
                </span>
              </div>

              {/* Event Properties List */}
              <div className="p-4 bg-atlas-950 rounded-xl border border-atlas-border space-y-2.5 font-mono text-xs">
                <div className="flex justify-between border-b border-slate-800 pb-1.5">
                  <span className="text-slate-500">e.type:</span>
                  <span className="text-amber-300 font-bold">"{lastEvent.type}"</span>
                </div>
                <div className="flex justify-between border-b border-slate-800 pb-1.5">
                  <span className="text-slate-500">e.target:</span>
                  <span className="text-sky-300 font-bold">{lastEvent.target}</span>
                </div>
                <div className="flex justify-between border-b border-slate-800 pb-1.5">
                  <span className="text-slate-500">e.key:</span>
                  <span className="text-emerald-300 font-bold">{lastEvent.key}</span>
                </div>
                <div className="flex justify-between border-b border-slate-800 pb-1.5">
                  <span className="text-slate-500">e.timeStamp:</span>
                  <span className="text-slate-300">{lastEvent.timeStamp}</span>
                </div>
                <div className="flex justify-between">
                  <span className="text-slate-500">e.defaultPrevented:</span>
                  <span className="text-slate-400">{String(lastEvent.defaultPrevented)}</span>
                </div>
              </div>
            </div>

            <div className="mt-4 pt-3 border-t border-atlas-border text-xs text-slate-400">
              Event handlers receive this `e` object automatically as the first parameter.
            </div>
          </ConceptCard>
        </div>
      </div>
    </section>
  );
}
